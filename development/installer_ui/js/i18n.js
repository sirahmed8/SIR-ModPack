function applyTranslations() {
  const lang = STATE.currentLang || 'en';
  const dict = I18N[lang] || I18N.en;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (key.startsWith('eulaPoint')) {
        const parts = dict[key].split(':');
        if (parts.length > 1) {
          el.innerHTML = `<strong class="text-title">${parts[0]}:</strong>${parts.slice(1).join(':')}`;
        } else {
          el.innerText = dict[key];
        }
      } else {
        el.innerText = dict[key];
      }
    }
  });

  const legalCard = document.getElementById('eula-summary-card');
  if (legalCard) {
    legalCard.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }

  const langInd = document.getElementById('lang-indicator');
  if (langInd) {
    langInd.innerText = lang === 'ar' ? 'English' : 'عربي';
  }

  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', lang);

  if (typeof updateNavButtons === 'function') {
    updateNavButtons();
  }

  if (typeof switchInstallerLegalDoc === 'function' && typeof STATE.currentLegalDoc !== 'undefined') {
    switchInstallerLegalDoc(STATE.currentLegalDoc || 'terms');
  }
}

function toggleLanguage() {
  STATE.currentLang = STATE.currentLang === 'ar' ? 'en' : 'ar';
  localStorage.setItem('sir_installer_lang', STATE.currentLang);
  applyTranslations();
}

window.toggleLanguage = toggleLanguage;
window.applyTranslations = applyTranslations;
